export function getFormatMeta(formatId: string): FormatMeta {
  const normalized = formatId.toLowerCase().replace(/^\./, "");
  if (FORMAT_META_MAP[normalized]) {
    return FORMAT_META_MAP[normalized];
  }
  const found = Object.values(FORMAT_META_MAP).find((m) =>
    m.extensions.includes(normalized),
  );
  if (found) return found;

  return {
    id: normalized,
    displayName: normalized.toUpperCase(),
    category: "document",
    subtitle: normalized.toUpperCase(),
    badgeBg: "bg-slate-100",
    badgeText: "text-slate-700",
    badgeBorder: "border-slate-200",
    iconBg: "bg-slate-200",
    iconText: "text-slate-600",
    extensions: [normalized],
  };
}

